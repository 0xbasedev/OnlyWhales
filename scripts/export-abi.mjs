// Writes typed ABIs for the frontend and server from Foundry's build output.
// Run after `forge build`: pnpm abi
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'

const targets = [
  ['OnlyWhalesVault', 'vaultAbi', 'vault'],
  ['WhalePass', 'passAbi', 'pass'],
]

mkdirSync('src/abi', { recursive: true })
for (const [contract, name, file] of targets) {
  const { abi } = JSON.parse(readFileSync(`out/${contract}.sol/${contract}.json`, 'utf8'))
  const body = `// Generated by scripts/export-abi.mjs from contracts/src/${contract}.sol. Do not edit.\nexport const ${name} = ${JSON.stringify(abi, null, 2)} as const\n`
  writeFileSync(`src/abi/${file}.ts`, body)
  console.log(`src/abi/${file}.ts  (${abi.length} entries)`)
}
